import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('.preview',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Users/gy/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.waitForTimeout(2200);
await page.screenshot({path:'.preview/desktop.png',fullPage:true});
console.log(JSON.stringify({title:await page.title(),webgl:await page.locator('body').evaluate(el=>!el.classList.contains('no-webgl')),canvasCount:await page.locator('canvas').count(),errors}));
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(1000);
await page.screenshot({path:'.preview/mobile.png',fullPage:true});
console.log(JSON.stringify({mobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors}));
await browser.close();
